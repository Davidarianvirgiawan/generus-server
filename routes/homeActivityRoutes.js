const express = require('express')
const config = require('../config')
const { protect, admin, student, parent } = require('../middlewares/authMiddleware')
const homeActivityController = require(`../modules/${config.APP_VERSION}/homeActivity/homeActivityController`)

const router = express.Router()
router.route('/logs')
    .get(protect, parent, homeActivityController.logs)
    .put(protect, parent, homeActivityController.check)
router.route('/children').get(protect, parent, homeActivityController.children)
router.route('/children/:studentId/activities').get(protect, parent, homeActivityController.childActivities)
router.route('/requests').get(protect, parent, homeActivityController.requests)
router.route('/requests/:studentId').put(protect, parent, homeActivityController.answerRequest)
router.route('/parent-search').get(protect, student, homeActivityController.parentSearch)
router.route('/parents')
    .get(protect, student, homeActivityController.myParents)
    .post(protect, student, homeActivityController.requestParent)
router.route('/parents/:parentId').delete(protect, student, homeActivityController.removeParent)
router.route('/report').get(protect, admin, homeActivityController.report)
router.route('/report/:studentId/download').get(protect, admin, homeActivityController.downloadStudentReport)
router.route('/report/:studentId').get(protect, admin, homeActivityController.studentReport)
router.route('/')
    .get(protect, homeActivityController.list)
    .post(protect, admin, homeActivityController.create)
router.route('/:id')
    .put(protect, admin, homeActivityController.update)
    .delete(protect, admin, homeActivityController.delete)

module.exports = router
